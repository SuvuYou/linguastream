import { execFile } from "child_process";
import { promisify } from "util";
import { promises as fs } from "fs";
import path from "path";
import os from "os";
import { getCurrentUser } from "@/lib/firebase/session";
import { z } from "zod";
import { db } from "@/lib/initializations/db";
import { JOB_STATUS, LanguageCode, SUPPORTED_LANGUAGES } from "@/helpers/const";
import { randomUUID } from "crypto";
import {
  normalizeAutoGenerated,
  parseVtt,
  parseVttForAutoGeneratedYT,
} from "@/lib/scripts/subtitle-parser";

const execFileAsync = promisify(execFile);
const YTDLP_PATH = "/Users/user/.pyenv/shims/yt-dlp";

// Base flags applied to every yt-dlp invocation: space requests out a bit to
// reduce how often YouTube's bot detection trips, and pin a proxy if set.
function baseYtDlpArgs(): string[] {
  const args = [
    "--sleep-requests",
    "1",
    "--min-sleep-interval",
    "2",
    "--max-sleep-interval",
    "5",
  ];

  return args;
}

export interface SubtitleInfo {
  available: Record<string, TrackEntry>;
  autoGenerated: Record<string, TrackEntry>;
  allLanguages: string[];
}

interface TrackEntry {
  ext: string;
  url: string;
}

interface VideoInfo {
  subtitles?: Record<string, TrackEntry[]>;
  automatic_captions?: Record<string, TrackEntry[]>;
}

async function getVideoInfo(videoId: string): Promise<VideoInfo> {
  const url = `https://www.youtube.com/watch?v=${videoId}`;

  const { stdout } = await execFileAsync(
    YTDLP_PATH,
    [...baseYtDlpArgs(), "-J", url],
    { timeout: 30_000 },
  );

  return JSON.parse(stdout);
}

function filterTracks(
  tracks?: Record<string, TrackEntry[]>,
): Record<string, TrackEntry> {
  if (!tracks) return {};

  return Object.fromEntries(
    Object.entries(tracks)
      .filter(([lang]) => SUPPORTED_LANGUAGES.has(lang as LanguageCode))
      .flatMap(([lang, entries]) => {
        const vtt = entries.find((entry) => entry.ext === "vtt");
        return vtt ? [[lang, vtt]] : [];
      }),
  );
}

export async function GET(req: NextRequest) {
  const user = await getCurrentUser();
  if (!user)
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  const videoId = req.nextUrl.searchParams.get("videoId");
  if (!videoId) {
    return NextResponse.json({ error: "Missing videoId" }, { status: 400 });
  }

  try {
    const info = await getVideoInfo(videoId);

    const available = filterTracks(info.subtitles);
    const autoGenerated = filterTracks(info.automatic_captions);

    const allLanguages = [
      ...new Set([...Object.keys(available), ...Object.keys(autoGenerated)]),
    ];

    return NextResponse.json({
      available,
      autoGenerated,
      allLanguages,
    } satisfies SubtitleInfo);
  } catch (err) {
    console.error("yt-dlp list-subs error:", err);
    return NextResponse.json(
      { error: "Failed to fetch subtitle list" },
      { status: 500 },
    );
  }
}

interface SubtitleTrack {
  language: string;
  isSource: boolean;
  isAutoGenerated: boolean;
}

// Note: we intentionally no longer accept a client-supplied caption `url`.
// Those URLs are short-lived and fetching them directly from Node is what
// triggered YouTube's 429s. Instead we re-derive the download ourselves via
// yt-dlp, using only the language + auto-generated flag from the client.
const SubtitleTrackSchema = z.object({
  language: z.string().min(2),
  isSource: z.boolean(),
  isAutoGenerated: z.boolean(),
});

const BodySchema = z.object({
  mediaId: z.string().uuid(),
  sourceLang: z.string().min(2),
  subtitleTracks: z.array(SubtitleTrackSchema),
  translateMethod: z.enum(["youtube", "libretranslate", "deepL"]),
});

/**
 * Downloads a single subtitle track by shelling out to yt-dlp, rather than
 * fetching a caption URL directly. yt-dlp mimics a real client handshake
 * (and can use a proxy) so it survives the bot-detection that blocks bare
 * `fetch()` calls to the timedtext endpoint.
 */
async function downloadSubtitleViaYtDlp(
  videoId: string,
  language: string,
  isAutoGenerated: boolean,
  retries = 3,
): Promise<string> {
  const url = `https://www.youtube.com/watch?v=${videoId}`;
  const outDir = await fs.mkdtemp(path.join(os.tmpdir(), "yt-subs-"));
  const outTemplate = path.join(outDir, "track.%(ext)s");

  const args = [
    ...baseYtDlpArgs(),
    isAutoGenerated ? "--write-auto-subs" : "--write-subs",
    "--skip-download",
    "--sub-langs",
    language,
    "--sub-format",
    "vtt",
    "-o",
    outTemplate,
    url,
  ];

  try {
    await execFileAsync(YTDLP_PATH, args, { timeout: 30_000 });

    const files = await fs.readdir(outDir);
    const vttFile = files.find((f) => f.endsWith(".vtt"));

    if (!vttFile) {
      throw new Error(`yt-dlp produced no subtitle file for ${language}`);
    }

    return await fs.readFile(path.join(outDir, vttFile), "utf-8");
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    const looksRateLimited = /429|rate.?limit/i.test(message);

    if (looksRateLimited && retries > 0) {
      console.warn(`yt-dlp rate-limited for ${language}, retrying in 5s...`);
      await sleep(5_000);
      return downloadSubtitleViaYtDlp(
        videoId,
        language,
        isAutoGenerated,
        retries - 1,
      );
    }

    throw new Error(`Failed to fetch subtitles for ${language}: ${message}`);
  } finally {
    await fs.rm(outDir, { recursive: true, force: true }).catch(() => {});
  }
}

async function fetchSubtitleLines(videoId: string, track: SubtitleTrack) {
  const raw = await downloadSubtitleViaYtDlp(
    videoId,
    track.language,
    track.isAutoGenerated,
  );

  if (track.isAutoGenerated)
    return normalizeAutoGenerated(parseVttForAutoGeneratedYT(raw));

  return parseVtt(raw);
}

export async function POST(req: NextRequest) {
  const user = await getCurrentUser();
  if (!user)
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  let body: unknown;
  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON" }, { status: 400 });
  }

  const parsed = BodySchema.safeParse(body);
  if (!parsed.success) {
    return NextResponse.json(
      { error: "Invalid request", details: parsed.error.flatten() },
      { status: 400 },
    );
  }

  const { mediaId, sourceLang, subtitleTracks, translateMethod } = parsed.data;

  if (translateMethod !== "youtube") {
    return NextResponse.json(
      {
        error: `Route not available for this translation method (${translateMethod})`,
      },
      { status: 400 },
    );
  }

  // video_id is read from our own record rather than trusted from the
  // client, so a caller can't point this job at an arbitrary video.
  const media = await db.mediaContent.findUnique({
    where: { id: mediaId },
    select: { user_id: true, job_status: true, youtube_video_id: true },
  });

  if (!media || media.user_id !== user.id) {
    return NextResponse.json({ error: "Not found" }, { status: 404 });
  }

  if (!media.youtube_video_id) {
    return NextResponse.json(
      { error: "Media has no associated YouTube video id" },
      { status: 400 },
    );
  }

  if (
    media.job_status === JOB_STATUS.RUNNING ||
    media.job_status === JOB_STATUS.PENDING
  ) {
    return NextResponse.json({ error: "Job already running" }, { status: 409 });
  }

  await db.mediaContent.update({
    where: { id: mediaId },
    data: { job_status: JOB_STATUS.PENDING, job_progress: 0 },
  });

  processYouTubeSubtitles({
    mediaContentId: mediaId,
    videoId: media.youtube_video_id,
    subtitleTracks,
    sourceLang,
  }).catch(async (err) => {
    console.error("YouTube subtitles processing error:", err);
    await db.mediaContent.update({
      where: { id: mediaId },
      data: { job_status: JOB_STATUS.ERROR, job_progress: 0 },
    });
  });

  return NextResponse.json({ ok: true, mediaId });
}

async function processYouTubeSubtitles({
  mediaContentId,
  videoId,
  subtitleTracks,
  sourceLang,
}: {
  mediaContentId: string;
  videoId: string;
  subtitleTracks: SubtitleTrack[];
  sourceLang: string;
}) {
  await db.mediaContent.update({
    where: { id: mediaContentId },
    data: { job_status: JOB_STATUS.RUNNING, job_progress: 5 },
  });

  const sourceTrack = subtitleTracks.find((e) => e.isSource);
  if (!sourceTrack) {
    throw new Error(`No source subtitles available for ${sourceLang}`);
  }

  const sourceLines = await fetchSubtitleLines(videoId, sourceTrack);

  if (!sourceLines) {
    throw new Error(`No subtitles available for ${sourceLang}`);
  }

  await db.mediaContent.update({
    where: { id: mediaContentId },
    data: { job_progress: 50 },
  });

  await upsertTrack(sourceLines, {
    mediaContentId,
    language: sourceLang,
    isSource: true,
  });

  // wait after fetchSubtitleLines to avoid hitting 429
  await sleep(5_000);

  await db.mediaContent.update({
    where: { id: mediaContentId },
    data: {
      source_language: sourceLang,
      job_progress: 75,
    },
  });

  const translationTracks = subtitleTracks.filter((e) => !e.isSource);

  for (const [index, track] of translationTracks.entries()) {
    const transLines = await fetchSubtitleLines(videoId, track);

    if (!transLines) {
      console.warn(`No YouTube subtitles for ${track.language}, skipping`);
      continue;
    }

    await upsertTrack(transLines, {
      mediaContentId,
      language: track.language,
      isSource: false,
    });

    if (index < translationTracks.length - 1) {
      await sleep(5_000);
    }
  }

  await db.mediaContent.update({
    where: { id: mediaContentId },
    data: { job_status: JOB_STATUS.DONE, job_progress: 100 },
  });
}

async function upsertTrack(
  lines: { index: number; start_ms: number; end_ms: number; text: string }[],
  trackData: { mediaContentId: string; language: string; isSource: boolean },
) {
  const existing = await db.subtitleTrack.findUnique({
    where: {
      media_content_id_language: {
        media_content_id: trackData.mediaContentId,
        language: trackData.language,
      },
    },
    select: { id: true },
  });

  if (existing) {
    await db.subtitleLine.deleteMany({
      where: { subtitle_track_id: existing.id },
    });
    await db.subtitleTrack.delete({ where: { id: existing.id } });
  }

  const track = await db.subtitleTrack.create({
    data: {
      media_content_id: trackData.mediaContentId,
      language: trackData.language,
      is_source: trackData.isSource,
    },
  });

  await db.subtitleLine.createMany({
    data: lines.map((l) => ({
      id: randomUUID(),
      media_content_id: trackData.mediaContentId,
      subtitle_track_id: track.id,
      index: l.index,
      start_ms: l.start_ms,
      end_ms: l.end_ms,
      text: l.text,
    })),
  });
}

function sleep(ms: number) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
